#!/usr/bin/env python3
"""Embed the guide images in the page itself, as the MCP guide page does (data: URIs, no files to fetch).

Run before `now-sdk build`:  python3 scripts/gen-public-images.py

Per page (lazy chunk) it writes src/client/content/images/<slug>.ts with { "<original file name>": "data:..." }
and src/client/content/images-index.ts. Pages load their chunk before rendering (see LabPage / Home).
Why: the old images were attachments and a visitor with no login is redirected to the login page for them.
Size: opaque PNG screenshots are stored as JPEG (quality 82, same pixel size); PNGs with transparency stay PNG;
GIF animations are stored as animated WebP (same size and timing), because three GIFs were 67 MB.
Also writes src/client/virtual-on/scene-source.ts (the animation script) so the page does not fetch it.
"""
import base64, io, json, os, re, sys, urllib.parse
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE = os.path.join(ROOT, 'src/fluent/lab-assets')
OUT = os.path.join(ROOT, 'src/client/content/images')

files = {}
for d in ('files', 'home'):
    for f in os.listdir(os.path.join(BASE, d)):
        if not f.startswith('.') and not f.endswith('.ts'):
            files[f] = os.path.join(BASE, d, f)
# Guide images that were never stored as attachments (for example the Integration Hub manual route screenshots).
EXTRA = os.path.join(ROOT, 'lab-guide/assets')
for f in os.listdir(EXTRA):
    if f not in files and not f.startswith('.') and f.rsplit('.', 1)[-1].lower() in ('png', 'gif', 'jpg', 'jpeg', 'svg'):
        files[f] = os.path.join(EXTRA, f)

def objtext(path):
    t = open(path, encoding='utf8').read()
    return json.loads('{' + t[t.index('= {') + 3:t.rindex('}')].rstrip().rstrip(',') + '}')

md = objtext(os.path.join(ROOT, 'src/client/content/lab-markdown.ts'))
mdc = objtext(os.path.join(ROOT, 'src/client/content/lab-markdown-clab.ts'))
pat = re.compile(r'[A-Za-z0-9_.\-%]+\.(?:png|gif|jpe?g|svg)', re.I)
routes = {}
for r, t in list(md.items()) + list(mdc.items()):
    routes.setdefault(r, set()).update(n for n in files if n in t or urllib.parse.quote(n) in t)
home = open(os.path.join(ROOT, 'src/client/pages/Home.tsx'), encoding='utf8').read()
routes['/home'] = {m for m in re.findall(r'asset\("([^"]+)"\)', home) if m in files}  # Overview is rendered by Home.tsx, not by its markdown

cache = {}
def data_uri(name):
    if name in cache: return cache[name]
    path = files[name]; ext = name.rsplit('.', 1)[1].lower()
    raw = open(path, 'rb').read()
    if ext == 'png':
        im = Image.open(path)
        alpha = im.mode in ('RGBA', 'LA', 'PA') or 'transparency' in im.info
        if alpha:
            alpha = im.convert('RGBA').getchannel('A').getextrema()[0] < 250
        if not alpha:
            b = io.BytesIO(); im.convert('RGB').save(b, 'JPEG', quality=82, optimize=True)
            out = ('image/jpeg', b.getvalue())
        else:
            out = ('image/png', raw)
    elif ext == 'gif':
        im = Image.open(path); frames = []; durs = []
        for i in range(getattr(im, 'n_frames', 1)):
            im.seek(i); frames.append(im.convert('RGBA').copy()); durs.append(im.info.get('duration', 100))
        b = io.BytesIO()
        frames[0].save(b, 'WEBP', save_all=True, append_images=frames[1:], duration=durs, loop=0, quality=70, method=4)
        out = ('image/webp', b.getvalue()) if len(b.getvalue()) < len(raw) else ('image/gif', raw)
    else:
        out = ({'jpg': 'image/jpeg', 'jpeg': 'image/jpeg', 'svg': 'image/svg+xml'}[ext], raw)
    cache[name] = 'data:%s;base64,%s' % (out[0], base64.b64encode(out[1]).decode())
    return cache[name]

os.makedirs(OUT, exist_ok=True)
for f in os.listdir(OUT):
    if f.endswith('.ts'): os.remove(os.path.join(OUT, f))
index = []; total = 0
for r in sorted(routes):
    names = sorted(routes[r])
    if not names: continue
    slug = r.strip('/').replace('/', '__') or 'root'
    body = ',\n'.join('    %s: %s' % (json.dumps(n), json.dumps(data_uri(n))) for n in names)
    src = '/* Generated by scripts/gen-public-images.py. Images of page %s embedded as data URIs. */\nconst IMAGES: Record<string, string> = {\n%s,\n}\nexport default IMAGES\n' % (r, body)
    open(os.path.join(OUT, slug + '.ts'), 'w', encoding='utf8').write(src)
    index.append('    %s: () => import(%s),' % (json.dumps(r), json.dumps('./images/' + slug)))
    total += len(src)
    print('%-52s %3d images  %6.1f MB' % (r, len(names), len(src) / 1e6))
open(os.path.join(ROOT, 'src/client/content/images-index.ts'), 'w').write(
    '/* Generated by scripts/gen-public-images.py. One lazy chunk per page. */\nexport const IMAGE_CHUNKS: Record<string, () => Promise<{ default: Record<string, string> }>> = {\n%s\n}\n' % '\n'.join(index))
scene = open(os.path.join(ROOT, 'public/virtual-on/scene.js'), encoding='utf8').read()
open(os.path.join(ROOT, 'src/client/virtual-on/scene-source.ts'), 'w', encoding='utf8').write(
    '/* Generated by scripts/gen-public-images.py from public/virtual-on/scene.js. */\nconst SCENE_JS: string = %s\nexport default SCENE_JS\n' % json.dumps(scene))
print('chunks total %.1f MB (largest page above), unique images embedded %d' % (total / 1e6, len(cache)))
