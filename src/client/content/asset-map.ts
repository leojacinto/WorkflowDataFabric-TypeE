/** Returns the platform attachment URL for a lab image URL, or the URL unchanged when it is not stored in the app. */
export function localAsset(url: string): string {
    let file = url.split('?')[0].split('/').pop() || ''
    try {
        file = decodeURIComponent(file)
    } catch {}
    const id = LAB_ATTACHMENTS[file]
    return id ? `/sys_attachment.do?sys_id=${id}` : url
}
